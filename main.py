def build(here):
    rows, land = load_data(here)
    used = []
    masthead(rows)
    spine(rows)
    heroes(rows, here, used)
    strip(rows)
    midgrid(rows)
    mapband(rows, land)
    index(rows)
    footer(rows)
    return used


def main():
    here = os.path.dirname(os.path.abspath(__file__))
    used = build(here)
    outdir = os.environ.get("MAKEFUN_OUTPUT_DIR", "/output")
    os.makedirs(outdir, exist_ok=True)
    with open(os.path.join(outdir, "entry.png"), "wb") as f:
        f.write(encode_png())
    for name, ok, why in used:
        print("hero", name, "media" if ok else "fallback:" + str(why))


if __name__ == "__main__":
    main()
