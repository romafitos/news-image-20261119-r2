BUF = bytearray(W * H * 3)
for _i in range(W * H):
    BUF[_i * 3] = PAPER[0]
    BUF[_i * 3 + 1] = PAPER[1]
    BUF[_i * 3 + 2] = PAPER[2]


def px(x, y, c):
    if 0 <= x < W and 0 <= y < H:
        o = (y * W + x) * 3
        BUF[o] = c[0]
        BUF[o + 1] = c[1]
        BUF[o + 2] = c[2]


def rect(x, y, w, h, c):
    x0 = max(0, x)
    y0 = max(0, y)
    x1 = min(W, x + w)
    y1 = min(H, y + h)
    if x1 <= x0 or y1 <= y0:
        return
    row = bytes(c) * (x1 - x0)
    for yy in range(y0, y1):
        o = (yy * W + x0) * 3
        BUF[o:o + len(row)] = row


def vgrad(x, y, w, h, top, bot):
    if h <= 0:
        return
    for yy in range(y, y + h):
        f = (yy - y) / max(1, h - 1)
        c = (round(top[0] + (bot[0] - top[0]) * f),
             round(top[1] + (bot[1] - top[1]) * f),
             round(top[2] + (bot[2] - top[2]) * f))
        rect(x, yy, w, 1, c)


def circle(cx, cy, r, c):
    for dy in range(-r, r + 1):
        dx = int(math.sqrt(max(0, r * r - dy * dy)))
        rect(cx - dx, cy + dy, dx * 2 + 1, 1, c)


def ellipse(cx, cy, rx, ry, c):
    for dy in range(-ry, ry + 1):
        if ry == 0:
            continue
        dx = int(rx * math.sqrt(max(0.0, 1.0 - (dy * dy) / (ry * ry))))
        rect(cx - dx, cy + dy, dx * 2 + 1, 1, c)


def poly(points, c):
    if len(points) < 3:
        return
    ys = [p[1] for p in points]
    for yy in range(min(ys), max(ys) + 1):
        xs = []
        n = len(points)
        for i in range(n):
            x1, y1 = points[i]
            x2, y2 = points[(i + 1) % n]
            if (y1 <= yy < y2) or (y2 <= yy < y1):
                if y2 != y1:
                    xs.append(x1 + (yy - y1) * (x2 - x1) / (y2 - y1))
        xs.sort()
        for k in range(0, len(xs) - 1, 2):
            rect(int(math.ceil(xs[k])), yy, int(math.floor(xs[k + 1])) - int(math.ceil(xs[k])) + 1, 1, c)


def line(x1, y1, x2, y2, c):
    dx = abs(x2 - x1)
    dy = -abs(y2 - y1)
    sx = 1 if x1 < x2 else -1
    sy = 1 if y1 < y2 else -1
    err = dx + dy
    x, y = x1, y1
    while True:
        px(x, y, c)
        if x == x2 and y == y2:
            break
        e2 = 2 * err
        if e2 >= dy:
            err += dy
            x += sx
        if e2 <= dx:
            err += dx
            y += sy


def outline(points, c):
    n = len(points)
    for i in range(n):
        x1, y1 = points[i]
        x2, y2 = points[(i + 1) % n]
        line(x1, y1, x2, y2, c)

