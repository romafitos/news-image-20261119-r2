# ---- PNG decoder (8/16-bit, grey/RGB/palette/grey+alpha/RGBA, filters 0-4) ----
class DecodeError(Exception):
    pass


def _paeth(a, b, c):
    p = a + b - c
    pa = abs(p - a)
    pb = abs(p - b)
    pc = abs(p - c)
    if pa <= pb and pa <= pc:
        return a
    if pb <= pc:
        return b
    return c


def decode_png(path):
    with open(path, "rb") as f:
        data = f.read()
    if data[:8] != b"\x89PNG\r\n\x1a\n":
        raise DecodeError("bad signature")
    pos = 8
    ihdr = None
    plte = None
    trns = None
    idat = bytearray()
    while pos < len(data):
        ln = struct.unpack(">I", data[pos:pos + 4])[0]
        typ = data[pos + 4:pos + 8]
        body = data[pos + 8:pos + 8 + ln]
        if typ == b"IHDR":
            ihdr = struct.unpack(">IIBBBBB", body)
        elif typ == b"PLTE":
            plte = body
        elif typ == b"tRNS":
            trns = body
        elif typ == b"IDAT":
            idat += body
        elif typ == b"IEND":
            break
        pos += 12 + ln
    if ihdr is None:
        raise DecodeError("no IHDR")
    w, h, depth, ctype, _comp, _filt, inter = ihdr
    if inter != 0:
        raise DecodeError("interlaced")
    if depth not in (8, 16):
        raise DecodeError("depth")
    if ctype not in (0, 2, 3, 4, 6):
        raise DecodeError("ctype")
    if w * h > 3000000:
        raise DecodeError("too big")
    nch = {0: 1, 2: 3, 3: 1, 4: 2, 6: 4}[ctype]
    bpp = nch * (depth // 8)
    stride = w * bpp
    raw = zlib.decompress(bytes(idat))
    if len(raw) != h * (1 + stride):
        raise DecodeError("size")
    rows = []
    prev = bytearray(stride)
    for yy in range(h):
        fb = raw[yy * (1 + stride)]
        cur = bytearray(raw[yy * (1 + stride) + 1:(yy + 1) * (1 + stride)])
        if fb == 1:
            for i in range(bpp, stride):
                cur[i] = (cur[i] + cur[i - bpp]) & 255
        elif fb == 2:
            for i in range(stride):
                cur[i] = (cur[i] + prev[i]) & 255
        elif fb == 3:
            for i in range(stride):
                left = cur[i - bpp] if i >= bpp else 0
                cur[i] = (cur[i] + (left + prev[i]) // 2) & 255
        elif fb == 4:
            for i in range(stride):
                a = cur[i - bpp] if i >= bpp else 0
                b = prev[i]
                c = prev[i - bpp] if i >= bpp else 0
                cur[i] = (cur[i] + _paeth(a, b, c)) & 255
        elif fb != 0:
            raise DecodeError("filter")
        rows.append(cur)
        prev = cur
    if depth == 16:
        rows = [bytearray(r[0::2]) for r in rows]
        bpp = nch
        stride = w * bpp

    def pixel(sx, sy):
        row = rows[sy]
        o = sx * bpp
        if ctype == 2:
            return (row[o], row[o + 1], row[o + 2])
        if ctype == 6:
            a = row[o + 3]
            if a == 255:
                return (row[o], row[o + 1], row[o + 2])
            return tuple((row[o + k] * a + 255 * (255 - a)) // 255 for k in range(3))
        if ctype == 0:
            return (row[o], row[o], row[o])
        if ctype == 3:
            idx = row[o] * 3
            return (plte[idx], plte[idx + 1], plte[idx + 2])
        a = row[o + 1]
        g = row[o]
        return tuple((g * a + 255 * (255 - a)) // 255 for _ in range(3))

    return w, h, pixel


def paste_cover(path, px0, py0, pw, ph):
    try:
        w, h, pixel = decode_png(path)
    except Exception as e:
        return False, str(e)
    s = max(pw / w, ph / h)
    sw = w * s
    sh = h * s
    ox = px0 - (sw - pw) / 2.0
    oy = py0 - (sh - ph) / 2.0
    for yy in range(ph):
        sy = int((yy + (sh - ph) / 2.0) / s)
        if sy < 0:
            sy = 0
        if sy >= h:
            sy = h - 1
        for xx in range(pw):
            sx = int((xx + (sw - pw) / 2.0) / s)
            if sx < 0:
                sx = 0
            if sx >= w:
                sx = w - 1
            px(px0 + xx, py0 + yy, pixel(sx, sy))
    return True, "media"

