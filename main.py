# ---- font scaling + text helpers ----
_CACHE = {}


def _scaled(font, ch, size):
    key = (font, ch, size)
    if key in _CACHE:
        return _CACHE[key]
    adv, rows = FONTS[font][ch]
    scale = size / 15.0
    out_h = max(1, round(20 * scale))
    out_w = max(1, round(20 * scale))
    src = []
    for r in range(20):
        grp = rows[r * 5:(r + 1) * 5]
        v = int(grp, 16)
        src.append([(v >> (19 - c)) & 1 for c in range(20)])
    runs = []
    for oy in range(out_h):
        fy0 = oy / scale
        fy1 = (oy + 1) / scale
        spans = []
        start = None
        for ox in range(out_w):
            fx0 = ox / scale
            fx1 = (ox + 1) / scale
            ink_area = 0.0
            for sy in range(int(math.floor(fy0)), min(20, int(math.ceil(fy1)))):
                ov_y = min(sy + 1, fy1) - max(sy, fy0)
                if ov_y <= 0:
                    continue
                for sx in range(int(math.floor(fx0)), min(20, int(math.ceil(fx1)))):
                    ov_x = min(sx + 1, fx1) - max(sx, fx0)
                    if ov_x <= 0:
                        continue
                    ink_area += ov_x * ov_y * src[sy][sx]
            total = (fx1 - fx0) * (fy1 - fy0)
            on = total > 0 and ink_area * 2 >= total
            if on and start is None:
                start = ox
            if (not on) and start is not None:
                spans.append((start, ox - 1))
                start = None
        if start is not None:
            spans.append((start, out_w - 1))
        runs.append(spans)
    adv_px = max(1, round(adv * scale))
    res = (adv_px, runs, round(2 * scale), out_h)
    _CACHE[key] = res
    return res


def text_w(s, font, size):
    return sum(_scaled(font, ch, size)[0] for ch in s)


def draw_text(x, y, s, font, size, color, align="left"):
    if align == "center":
        x = x - text_w(s, font, size) // 2
    elif align == "right":
        x = x - text_w(s, font, size)
    pen = x
    for ch in s:
        adv, runs, left, _h = _scaled(font, ch, size)
        gx = pen - left
        for oy, spans in enumerate(runs):
            for (a, b) in spans:
                rect(gx + a, y + oy, b - a + 1, 1, color)
        pen += adv
    return pen


def wrap_lines(s, font, size, width):
    words = s.split(" ")
    lines = []
    cur = ""
    for w in words:
        t = w if not cur else cur + " " + w
        if text_w(t, font, size) <= width or not cur:
            cur = t
        else:
            lines.append(cur)
            cur = w
    if cur:
        lines.append(cur)
    return lines


def trunc(s, font, size, width):
    if text_w(s, font, size) <= width:
        return s
    while s and text_w(s + "…", font, size) > width:
        s = s[:-1]
    return s + "…"


def changes_block(x, y, text, font, size, width, max_lines, step, band=False):
    full = "WHAT CHANGES: " + text
    lines = wrap_lines(full, font, size, width)[:max_lines]
    if len(wrap_lines(full, font, size, width)) > max_lines and lines:
        lines[-1] = trunc(lines[-1], font, size, width)
    if band:
        rect(x - 4, y - 3, width + 8, len(lines) * step + 2, BAND)
    for i, ln in enumerate(lines):
        draw_text(x, y + i * step, ln, font, size, INK)
    return y + len(lines) * step

